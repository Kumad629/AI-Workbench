test('bound Yuanbao history prevents deletion during sync and disconnects after confirmed deletion',async()=>{
 const dir=mkdtempSync(join(tmpdir(),'awb-delete-web-'));let app;
 try{
  app=await electron.launch({args:[root],env:{...process.env,AI_WORKBENCH_DATA_DIR:dir}});
  const page=await app.firstWindow();
  const pair=JSON.parse((await page.evaluate(()=>window.workbench.call('browserBridgeInfo'))).pairing);
  const request=async(action,data)=>{
   const response=await fetch(pair.url+'/web-chat/'+action,{method:'POST',headers:{'Content-Type':'application/json',Authorization:'Bearer '+pair.token,Origin:'chrome-extension://'+'a'.repeat(32)},body:JSON.stringify(data)});
   return {status:response.status,data:await response.json()};
  };
  const clientId='12345678-1234-1234-1234-123456789abc',url='https://yuanbao.tencent.com/chat/menu-fixture';
  const binding=(await request('bind',{clientId,url,ready:true,historyEnabled:true})).data;
  expect(binding.bindingId).toBeTruthy();
  const auth={clientId,...binding};
  let status=await page.evaluate(()=>window.workbench.call('webChatStatus'));
  const loaded=await request('history',{...auth,url,requestId:status.history.id,messages:[{role:'user',content:'网页历史问题'},{role:'assistant',content:'网页历史回答'}]});
  expect(loaded.data.accepted).toBe(true);
  const id=loaded.data.conversationId;
  await page.evaluate(bindingId=>window.workbench.call('webChatHistory',{bindingId}),binding.bindingId);
  await page.locator('.conversation-item').filter({hasText:'网页历史问题'}).click({button:'right'});
  await page.getByRole('menuitem',{name:'删除',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'删除会话'});
  await dialog.getByRole('button',{name:'永久删除'}).click();
  await expect(dialog.getByRole('alert')).toContainText('等待网页历史同步');
  expect((await page.evaluate(()=>window.workbench.call('snapshot'))).conversations).toHaveLength(1);
  status=await page.evaluate(()=>window.workbench.call('webChatStatus'));
  await page.evaluate(()=>window.workbench.call('webChatCancel'));
  await dialog.getByRole('button',{name:'永久删除'}).click();
  await expect(dialog).not.toBeVisible();
  expect((await page.evaluate(()=>window.workbench.call('webChatStatus'))).bindingId).toBeUndefined();
  const late=await request('history',{...auth,url,requestId:status.history.id,messages:[{role:'user',content:'late'}]});
  expect(late.status).toBe(400);
  expect((await page.evaluate(()=>window.workbench.call('snapshot'))).conversations).toHaveLength(0);
 }finally{if(app)await app.close();rmSync(dir,{recursive:true,force:true});}
});
